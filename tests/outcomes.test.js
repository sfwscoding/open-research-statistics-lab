"use strict";
const assert=require("node:assert/strict");
const {Outcomes}=require("../outcomes.js");
const near=(x,y,tol=1e-9)=>assert.ok(Math.abs(x-y)<tol,`expected ${y}, got ${x}`);
let t=Outcomes.paired([1,2,3,4],[2,3,4,5]);
near(t.mean,1);near(t.p,0);assert.equal(t.df,3);
t=Outcomes.paired([1,2,3,4],[1,2,3,4]);near(t.t,0);near(t.p,1);
t=Outcomes.paired([1,2,3,4],[2,2,4,4]);near(t.mean,.5);near(t.t,Math.sqrt(3));near(t.p,0.18169011381620923,1e-8);
let w=Outcomes.wilcoxon([0,0,0,0],[1,2,3,4]);near(w.wPlus,10);near(w.p,.125);
w=Outcomes.wilcoxon([0,0,0,0],[1,-1,2,-2]);near(w.p,1);
w=Outcomes.wilcoxon([1,2,3],[1,2,3]);near(w.p,1);assert.equal(w.n,0);
near(Outcomes.binomial(3,2,.5),.5);near(Outcomes.binomial(23,19,.7),0.13560296695947663,1e-9);
